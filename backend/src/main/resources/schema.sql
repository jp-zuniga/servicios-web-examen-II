CREATE TABLE IF NOT EXISTS equipo (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_patrimonial VARCHAR(50)  NOT NULL UNIQUE,
    nombre             VARCHAR(100) NOT NULL,
    tipo               VARCHAR(20)  NOT NULL CHECK (tipo IN ('PORTATIL', 'PROYECTOR', 'TABLETA')),
    estado             VARCHAR(20)  NOT NULL CHECK (estado IN ('DISPONIBLE', 'PRESTADO'))
);

CREATE TABLE IF NOT EXISTS prestamo (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipo_id                 BIGINT       NOT NULL REFERENCES equipo (id),
    nombre_solicitante        VARCHAR(100) NOT NULL,
    fecha_prestamo            DATE         NOT NULL,
    fecha_devolucion_prevista DATE         NOT NULL,
    fecha_devolucion          DATE,
    estado                    VARCHAR(20)  NOT NULL CHECK (estado IN ('ACTIVO', 'DEVUELTO')),
    CONSTRAINT ck_prestamo_fechas
    CHECK (fecha_devolucion_prevista >= fecha_prestamo)
);

CREATE INDEX
IF NOT EXISTS ix_prestamo_equipo
ON prestamo (equipo_id);

CREATE UNIQUE INDEX
IF NOT EXISTS ux_prestamo_equipo_activo
ON prestamo (equipo_id)
WHERE estado = 'ACTIVO';
